class TestForce:
    def test_force_overwrites_makefile(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        makefile = tmp_path / "Makefile"
        makefile.write_text("# stale\n")

        result = runner.invoke(
            app, ["init", "--repo", str(tmp_path), "--force"]
        )
        assert result.exit_code == 0
        assert "Auto-generated by Sange" in makefile.read_text()

    def test_force_overwrites_fragments(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        frag = tmp_path / ".sange" / "makefiles" / "_core" / "help.mk"
        frag.write_text("# stale\n")

        runner.invoke(app, ["init", "--repo", str(tmp_path), "--force"])
        assert "# stale" not in frag.read_text()


