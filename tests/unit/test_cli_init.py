"""Tests for src/sange/cli/init.py — `sange init`."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from sange.cli import app


@pytest.fixture
def runner() -> CliRunner:
    return CliRunner()


# --------------------------------------------------------------------------- #
# Fresh init
# --------------------------------------------------------------------------- #


class TestFreshInit:
    def test_creates_sange_skeleton(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        result = runner.invoke(app, ["init", "--repo", str(tmp_path)])
        assert result.exit_code == 0, result.output
        assert (tmp_path / ".sange").is_dir()
        assert (tmp_path / ".sange" / "commits").is_dir()
        assert (tmp_path / ".sange" / "telemetry").is_dir()

    def test_creates_makefile_shim(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        makefile = tmp_path / "Makefile"
        assert makefile.is_file()
        content = makefile.read_text()
        assert "Auto-generated by Sange" in content
        assert ".sange/makefiles/" in content

    def test_creates_makefile_fragments(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        mk_dir = tmp_path / ".sange" / "makefiles"
        assert (mk_dir / "_core" / "help.mk").is_file()
        assert (mk_dir / "_core" / "env.mk").is_file()
        assert (mk_dir / "_core" / "colors.mk").is_file()
        assert (mk_dir / "vcs" / "git.mk").is_file()
        assert (mk_dir / "lang" / "python.mk").is_file()

    def test_creates_gitignore(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        gi = tmp_path / ".gitignore"
        assert gi.is_file()
        text = gi.read_text()
        assert "/Makefile" in text
        assert "/.sange/commits/" in text
        assert "/.sange/telemetry/" in text


# --------------------------------------------------------------------------- #
# Idempotency
# --------------------------------------------------------------------------- #


class TestIdempotent:
    def test_re_run_does_not_overwrite(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        # User edits the Makefile.
        makefile = tmp_path / "Makefile"
        makefile.write_text("# user-edited\n")

        # Re-run init without --force.
        result = runner.invoke(app, ["init", "--repo", str(tmp_path)])
        assert result.exit_code == 0
        assert makefile.read_text() == "# user-edited\n"
        assert "skipped" in result.output

    def test_re_run_does_not_double_gitignore(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        gitignore_first = (tmp_path / ".gitignore").read_text()
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        gitignore_second = (tmp_path / ".gitignore").read_text()
        # Bytes must be identical on the second run.
        assert gitignore_first == gitignore_second

    def test_re_run_repairs_missing_dir(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        # Operator manually nukes .sange/telemetry.
        import shutil

        shutil.rmtree(tmp_path / ".sange" / "telemetry")
        # Re-init heals.
        result = runner.invoke(app, ["init", "--repo", str(tmp_path)])
        assert result.exit_code == 0
        assert (tmp_path / ".sange" / "telemetry").is_dir()


