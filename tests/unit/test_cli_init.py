# --------------------------------------------------------------------------- #
# JSON mode
# --------------------------------------------------------------------------- #


class TestJsonMode:
    def test_json_emits_action_log(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        result = runner.invoke(
            app, ["--json", "init", "--repo", str(tmp_path)]
        )
        assert result.exit_code == 0
        payload = json.loads(result.output)
        assert payload["repo"] == str(tmp_path.resolve())
        assert isinstance(payload["actions"], list)
        # Every action has kind + status keys.
        for a in payload["actions"]:
            assert "status" in a

    def test_json_idempotent_run_shows_skipped(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        result = runner.invoke(
            app, ["--json", "init", "--repo", str(tmp_path)]
        )
        payload = json.loads(result.output)
        statuses = [a["status"] for a in payload["actions"]]
        assert "skipped" in statuses or "exists" in statuses
        assert "already-present" in statuses


