# --------------------------------------------------------------------------- #
# Gitignore preservation
# --------------------------------------------------------------------------- #


class TestGitignorePreservation:
    def test_appends_to_existing_gitignore(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        (tmp_path / ".gitignore").write_text("*.pyc\n.env\n")
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        text = (tmp_path / ".gitignore").read_text()
        # User entries preserved.
        assert "*.pyc" in text
        assert ".env" in text
        # Sange entries added.
        assert "/Makefile" in text
        assert "/.sange/commits/" in text

    def test_gitignore_already_has_some_entries(
        self, runner: CliRunner, tmp_path: Path
    ) -> None:
        # User already has /Makefile; init should only add the missing two.
        (tmp_path / ".gitignore").write_text("/Makefile\n")
        runner.invoke(app, ["init", "--repo", str(tmp_path)])
        text = (tmp_path / ".gitignore").read_text()
        # /Makefile appears exactly once.
        assert text.count("/Makefile") == 1
        assert "/.sange/commits/" in text


