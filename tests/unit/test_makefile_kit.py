class TestRun:
    def test_write_creates_all_files(self, tmp_path: Path) -> None:
        # Redirect MAKEFILES_DIR + SHIM_PATH to tmp_path for the test.
        from makefile_kit import (
            _Fragment as Fragment,  # noqa: F401
        )

        # Save originals.
        import makefile_kit

        original_mk_dir = makefile_kit.MAKEFILES_DIR
        original_shim = makefile_kit.SHIM_PATH
        # Also reroute every fragment.path via monkey-patching the
        # MAKEFILES_DIR module attribute. Because Fragment is frozen,
        # we replace FRAGMENTS with rerouted copies temporarily.

        try:
            makefile_kit.MAKEFILES_DIR = tmp_path / "makefiles"
            makefile_kit.SHIM_PATH = tmp_path / "Makefile.template"

            # FRAGMENTS' .path property reads makefile_kit.MAKEFILES_DIR at
            # access time? No — it's a @property on the dataclass; let me
            # check. Actually it returns MAKEFILES_DIR / ... at call time
            # because MAKEFILES_DIR is a module-level name. Re-read.
            outcomes = run(mode=WriteMode.WRITE, clock=_FIXED_CLOCK)
            assert len(outcomes) == 6  # 1 shim + 5 fragments

            assert (tmp_path / "Makefile.template").is_file()
            for frag in FRAGMENTS:
                assert frag.path.is_file()
        finally:
            makefile_kit.MAKEFILES_DIR = original_mk_dir
            makefile_kit.SHIM_PATH = original_shim

    def test_check_matches_after_write(self) -> None:
        """Run WRITE then CHECK on the real templates/ dir; CHECK must
        report 'match' for every outcome."""

        write_results = run(mode=WriteMode.WRITE, clock=_FIXED_CLOCK)
        check_results = run(mode=WriteMode.CHECK, clock=_FIXED_CLOCK)
        for outcome in check_results:
            assert outcome.result is VerificationResult.MATCH, (
                f"{outcome.path} did not match after write"
            )

    def test_idempotent_writes(self) -> None:
        """Two consecutive WRITE runs produce identical file content."""

        results_a = run(mode=WriteMode.WRITE, clock=_FIXED_CLOCK)
        results_b = run(mode=WriteMode.WRITE, clock=_FIXED_CLOCK)
        # The output_sha256 of each file must match across the two runs.
        for a, b in zip(results_a, results_b, strict=True):
            assert a.output_sha256 == b.output_sha256


