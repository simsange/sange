_MAKE = shutil.which("make")


@pytest.mark.skipif(_MAKE is None, reason="make not on PATH")
class TestRealMake:
    def _setup_kit(self, tmp_path: Path) -> Path:
        target = tmp_path / "kit-test"
        target.mkdir()
        makefiles_target = target / ".sange" / "makefiles"
        makefiles_target.mkdir(parents=True)
        # Copy live emitted files (we just wrote them in the previous
        # test class).
        for frag in FRAGMENTS:
            dest = makefiles_target / frag.category / f"{frag.name}.mk"
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(frag.path, dest)
        shutil.copy(SHIM_PATH, target / "Makefile")
        return target

    def test_make_help_succeeds(self, tmp_path: Path) -> None:
        target = self._setup_kit(tmp_path)
        result = subprocess.run(
            [_MAKE, "help"],
            cwd=str(target),
            capture_output=True,
            text=True,
            timeout=10,
        )
        assert result.returncode == 0, (
            f"make help failed: stdout={result.stdout!r} stderr={result.stderr!r}"
        )

    def test_make_help_lists_known_targets(self, tmp_path: Path) -> None:
        target = self._setup_kit(tmp_path)
        result = subprocess.run(
            [_MAKE, "help"],
            cwd=str(target),
            capture_output=True,
            text=True,
            timeout=10,
        )
        # Strip ANSI codes for a clean substring check.
        import re
        plain = re.sub(r"\x1b\[[0-9;]*m", "", result.stdout)
        for expected in (
            "help", "git-status", "git-log", "git-commit",
            "python-test", "python-lint",
        ):
            assert expected in plain, f"missing {expected!r} in help output"

    def test_make_help_default_target(self, tmp_path: Path) -> None:
        """No args = help (per `.DEFAULT_GOAL := help`)."""

        target = self._setup_kit(tmp_path)
        result = subprocess.run(
            [_MAKE], cwd=str(target), capture_output=True, text=True, timeout=10,
        )
        assert result.returncode == 0
        assert "help" in result.stdout.lower() or "Show available targets" in result.stdout
