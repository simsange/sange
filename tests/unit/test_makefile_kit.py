class TestShim:
    def test_starts_with_auto_generated_marker(self) -> None:
        assert _SHIM.startswith("# Auto-generated by Sange")

    def test_includes_all_categories(self) -> None:
        for cat in CATEGORY_ORDER:
            assert f"-include .sange/makefiles/{cat}/*.mk" in _SHIM

    def test_includes_core_first(self) -> None:
        # _core must appear before any category.
        core_idx = _SHIM.find("_core/*.mk")
        for cat in CATEGORY_ORDER:
            cat_idx = _SHIM.find(f"{cat}/*.mk")
            assert core_idx < cat_idx, f"{cat} must follow _core"

    def test_local_last_and_tolerant(self) -> None:
        # _local must use -include (leading dash) AND be the last include.
        lines = [
            line for line in _SHIM.splitlines() if "include " in line
        ]
        last_include = lines[-1]
        assert "_local" in last_include
        assert last_include.lstrip().startswith("-include")

    def test_default_goal_is_help(self) -> None:
        assert ".DEFAULT_GOAL := help" in _SHIM


